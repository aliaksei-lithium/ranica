// Copies the OFL fonts used by the page from @fontsource packages into public/fonts
// and writes public/fonts/fonts.css. Run once after changing the font list: `npm run fonts`.
// Only woff2 and only latin, latin-ext, cyrillic, cyrillic-ext subsets are kept.
import { readFileSync, writeFileSync, copyFileSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { join } from 'node:path';

const FONTS = [
  { pkg: 'playfair-display', files: ['700.css', '900.css'] },
  { pkg: 'pt-serif', files: ['400.css', '400-italic.css', '700.css', '700-italic.css'] },
  { pkg: 'ibm-plex-sans', files: ['400.css', '500.css', '600.css'] },
];
const SUBSETS = ['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext'];
const OUT = 'public/fonts';

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

let css = '/* Generated by scripts/copy-fonts.mjs. Fonts are licensed under SIL OFL 1.1. */\n';
for (const { pkg, files } of FONTS) {
  const dir = join('node_modules/@fontsource', pkg);
  for (const file of files) {
    const blocks = readFileSync(join(dir, file), 'utf8').split(/(?=\/\* )/);
    for (const block of blocks) {
      const name = block.match(/\/\* (\S+) \*\//)?.[1];
      if (!name) continue;
      const subset = name.slice(pkg.length + 1).replace(/-\d{3}-(normal|italic)$/, '');
      if (!SUBSETS.includes(subset)) continue;
      const woff2 = `${name}.woff2`;
      copyFileSync(join(dir, 'files', woff2), join(OUT, woff2));
      css += block
        .replace(/src: [^;]+;/, `src: url(/fonts/${woff2}) format('woff2');`)
        .replace('font-display: swap;', 'font-display: block;');
    }
  }
  copyFileSync(join(dir, 'LICENSE'), join(OUT, `LICENSE-${pkg}.txt`));
}
writeFileSync(join(OUT, 'fonts.css'), css);
console.log(`${readdirSync(OUT).length} files written to ${OUT}`);
